def test_appended_disclaimer_is_valid_openui_when_node_is_available(tmp_path: Path) -> None:
    dependencies = DEFAULT_VALIDATOR_PATH.parents[1] / "node_modules" / "@openuidev" / "react-lang"
    if shutil.which("node") is None or not dependencies.is_dir():
        pytest.skip("Node.js and the OpenUI validator dependencies are not available.")
    answer = f"Revenue was 100.\n\n{SPANISH_DISCLAIMER}\n\n{PROVENANCE}"
    completions = FakeCompletions('root = Card([title])\ntitle = TextContent("Revenue was 100.")')

    result = asyncio.run(_converter(tmp_path, completions).convert(answer, "es"))

    asyncio.run(NodeOpenUIParser().validate(result.text))


def test_empty_conversion_is_an_error(tmp_path: Path) -> None:
    completions = FakeCompletions("   ")
    with pytest.raises(ConnectorError, match="empty"):
        asyncio.run(_converter(tmp_path, completions).convert("answer"))
    assert completions.calls == 1


